CREATE TABLE public.post_comments AS
SELECT id AS post_id
FROM public.posts
WITH NO DATA;

ALTER TABLE public.post_comments
  ALTER COLUMN post_id SET NOT NULL,
  ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN user_id uuid NOT NULL
    CONSTRAINT post_comments_user_id_profiles_fkey
    REFERENCES public.profiles (id)
    ON DELETE CASCADE,
  ADD COLUMN content text NOT NULL
    CHECK (length(trim(content)) BETWEEN 1 AND 1000),
  ADD COLUMN created_at timestamptz NOT NULL DEFAULT now(),
  ADD CONSTRAINT post_comments_pkey PRIMARY KEY (id),
  ADD CONSTRAINT post_comments_post_id_fkey
    FOREIGN KEY (post_id)
    REFERENCES public.posts (id)
    ON DELETE CASCADE;

CREATE INDEX post_comments_post_id_created_at_idx
  ON public.post_comments (post_id, created_at);

ALTER TABLE public.post_comments ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Comments on visible posts are publicly readable"
  ON public.post_comments
  FOR SELECT
  TO anon, authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.posts
      WHERE posts.id = post_comments.post_id
        AND (
          posts.is_approved IS TRUE
          OR posts.submitted_by = auth.uid()
        )
    )
  );

CREATE POLICY "Authenticated users can comment on approved posts"
  ON public.post_comments
  FOR INSERT
  TO authenticated
  WITH CHECK (
    auth.uid() = user_id
    AND EXISTS (
      SELECT 1
      FROM public.posts
      WHERE posts.id = post_comments.post_id
        AND posts.is_approved IS TRUE
    )
  );

GRANT SELECT ON public.post_comments TO anon, authenticated;
GRANT INSERT ON public.post_comments TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.post_comments_id_seq TO authenticated;
